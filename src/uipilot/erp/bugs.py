"""可植入的缺陷目录。

测试 Agent 的评测靠它：每次运行前选一组缺陷打开，看 Agent 能找出几个。
`oracle` 表示这个缺陷会不会留下确定性信号（控制台报错、HTTP 5xx）；
没有信号的缺陷只能靠"读懂业务规则、发现结果不对"来找，这正是要测的能力。
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class Bug:
    id: str
    title: str
    rule: str  # 违反了帮助页里的哪条规则
    oracle: bool  # 是否会触发控制台报错或 5xx
    how: str  # 触发方式，只给评分用，不给 Agent 看


CATALOG: dict[str, Bug] = {
    b.id: b
    for b in [
        Bug("B01", "采购单合计丢掉了单价的小数部分", "R3", False, "明细单价带小数时，详情页和列表的合计按整数单价计算"),
        Bug("B02", "采购单列表第 2 页重复了第 1 页最后一条", "R4", False, "翻页偏移量少算 1"),
        Bug("B03", "供应商搜索只匹配名称开头", "R6", False, "搜索名称中间的字（如“电子”）查不到"),
        Bug("B04", "删除采购单删掉的是另一张", "R9", False, "确认删除后被删的是编号相邻的上一张，所选单据还在"),
        Bug("B05", "备注超过 50 字时保存报 500", "R7", True, "规则允许 200 字，51 字以上服务器报错"),
        Bug("B06", "数量可以填负数", "R2", False, "数量为负数时仍然保存成功"),
        Bug("B07", "日期的月和日被对调", "R10", False, "日小于等于 12 时，保存后的日期月日互换"),
        Bug("B08", "发票税额总按 6% 计算", "R8", False, "选 13% 或 9% 时，税额仍按 6% 算"),
        Bug("B09", "编辑采购单保存后最后一行明细丢失", "R3", False, "编辑页直接保存，最后一行明细被删除"),
        Bug("B10", "供应商税号可以重复", "R5", False, "新建供应商时用已存在的税号也能保存"),
        Bug("B11", "添加第 6 行明细时前端报错", "R11", True, "第 6 次点“添加明细行”抛出 TypeError，行没有加上"),
        Bug("B12", "按金额排序是按字符串排的", "R4", False, "按金额排序时 1000 排在 200 前面"),
        Bug("B13", "登记发票后采购单状态没变", "R8", False, "发票关联采购单后，采购单仍显示“待开票”"),
        Bug("B14", "已开票的采购单还能删除", "R9", False, "已开票采购单的删除按钮可用，确认后真的被删"),
    ]
}


def describe(ids: list[str]) -> str:
    return "\n".join(f"{i}: {CATALOG[i].title}（{CATALOG[i].rule}）— {CATALOG[i].how}" for i in ids)
