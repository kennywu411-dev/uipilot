        day = 3 + (i * 7) % 25
        n_lines = rng.randint(1, 4)
        lines = []
        for pid in rng.sample(range(1, len(PRODUCTS) + 1), n_lines):
            qty = rng.choice([5, 10, 20, 50, 100, 200, 500, 1000])
            lines.append((pid, qty, PRODUCTS[pid - 1][3]))
